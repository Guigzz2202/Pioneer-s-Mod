    /** io d'une absorbee pour un NBT de cette version des cases (null : inconnue). */
    @org.jetbrains.annotations.Nullable
    public static int[] io(String key, int nbtVersion) {
        int[][] chain = IO.get(key);
        if (chain == null) {
            return null;
        }
        for (int[] row : chain) {
            if (nbtVersion < row[0]) {
                return java.util.Arrays.copyOfRange(row, 1, 7);
            }
        }
        return java.util.Arrays.copyOfRange(chain[chain.length - 1], 1, 7);
    }
